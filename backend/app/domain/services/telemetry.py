# Prohibited causal connectors and diagnostic words in telemetry statements
_CAUSAL_FORBIDDEN = re.compile(
    r"\b(cause|caused|causing|root cause|culprit|responsible for|due to|because of|fault of)\b",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class TelemetryReading:
    """A deterministic, read-only telemetry measurement point."""

    entity_id: str
    entity_label: str
    metric_name: str
    value: float
    unit: str
    status: str  # "OK" | "WARNING" | "CRITICAL" | "UNKNOWN"
    provider: str  # "Datadog APM" | "Prometheus" | "CloudWatch"
    timestamp: int
    formatted: str
    threshold: float | None = None
    raw_payload: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "entityId": self.entity_id,
            "entityLabel": self.entity_label,
            "metricName": self.metric_name,
            "value": self.value,
            "unit": self.unit,
            "status": self.status,
            "provider": self.provider,
            "timestamp": self.timestamp,
            "formatted": self.formatted,
            "threshold": self.threshold,
            "rawPayload": self.raw_payload,
        }


