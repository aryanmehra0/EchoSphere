    def _resolve_entity_key(self, raw_entity: str) -> str:
        """Resolve a natural or colloquial entity string to a catalog key."""
        token = (raw_entity or "").strip().lower().replace("_", "-")
        if not token:
            return "redis"
        if "redis" in token or "cache" in token:
            return "redis"
        if "replica" in token:
            return "postgres-replica"
        if "postgres" in token or "db" in token or "database" in token or "psql" in token:
            return "postgres"
        if "checkout" in token or "cart" in token or "payment" in token and "stripe" not in token:
            return "checkout"
        if "auth" in token or "jwt" in token or "token" in token:
            return "auth"
        if "net" in token or "vpc" in token or "packet" in token or "drop" in token:
            return "network"
        if "stripe" in token or "card" in token or "gateway" in token and "ingress" not in token:
            return "stripe"
        if "ingress" in token or "proxy" in token or "edge" in token or "envoy" in token:
            return "ingress"
        return token

    @staticmethod
    def _status_for(value: float, threshold: float | None) -> str:
        """
        Derive OK/WARNING/CRITICAL from a live value against its threshold.

        Every metric in this catalog is "higher is worse" (utilization,
        latency, error/drop/timeout rate), so a single ratio-based rule
        covers all of them without per-metric special-casing. A metric with
        no threshold at all (there are none today, but a future addition
        might omit one) reports OK rather than raising.
        """
        if threshold is None or threshold <= 0:
            return "OK"
        if value < threshold:
            return "OK"
        if value < threshold * 1.5:
            return "WARNING"
        return "CRITICAL"

    @staticmethod
    def _format_live(label: str, metric_key: str, value: float, unit: str, threshold: float | None) -> str:
        """
        Generic formatter for a genuinely-queried value.

        Deliberately does not invent sub-metrics the way the static catalog's
        `formatted` strings do ("2.7 GB / 8.0 GB max", "142 client
        connections") — those numbers came from nowhere but this file. A
        live Prometheus query only proves the one number it asked for.
        """
        metric_label = metric_key.replace("_", " ")
        text = f"{label} {metric_label} is {value:g}{unit}"
        if threshold is not None:
            text += f" (threshold: {threshold:g}{unit})"
        return text

    async def probe(
        self,
        entity: str,
        metric: str | None = None,
        project_id: str | None = None,
    ) -> TelemetryReading:
        """
        Execute a read-only telemetry probe against Prometheus, falling back
        to the static catalog when no live Prometheus is reachable.
        """
        ts = now_ms()
        key = self._resolve_entity_key(entity)

        if key in self._catalog:
            entry = self._catalog[key]
            metric_key = metric or entry["default_metric"]
            metrics = entry["metrics"]
            if metric_key not in metrics:
                metric_key = entry["default_metric"]

            m = metrics[metric_key]
            threshold = m.get("threshold")
            promql = m.get("promql")

            if promql:
                from app.infrastructure import prometheus_client

                live_value = await prometheus_client.instant_query(promql)
                if live_value is not None:
                    raw_payload: dict[str, Any] = {"promql": promql, "source": "prometheus-live"}

                    logql = m.get("logql")
                    if logql:
                        from app.infrastructure import loki_client

                        log_lines = await loki_client.query_range(logql, limit=1)
                        if log_lines:
                            raw_payload["recentLog"] = log_lines[0]

                    return TelemetryReading(
                        entity_id=key,
                        entity_label=entry["label"],
                        metric_name=metric_key,
                        value=live_value,
                        unit=m["unit"],
                        status=self._status_for(live_value, threshold),
                        provider="Prometheus",
                        timestamp=ts,
                        formatted=self._format_live(entry["label"], metric_key, live_value, m["unit"], threshold),
                        threshold=threshold,
                        raw_payload=raw_payload,
                    )
                log.debug("telemetry: live query for %s (%s) returned no data; using static fallback", key, promql)

            return TelemetryReading(
                entity_id=key,
                entity_label=entry["label"],
                metric_name=metric_key,
                value=float(m["value"]),
                unit=m["unit"],
                status=m["status"],
                provider=entry["provider"],
                timestamp=ts,
                formatted=m["formatted"],
                threshold=threshold,
                raw_payload={**m.get("raw", {}), "source": "static-fallback"},
            )

        # Fallback for any unknown or dynamically extracted entity
        display_label = entity.replace("-", " ").title()
        return TelemetryReading(
            entity_id=key,
            entity_label=display_label,
            metric_name=metric or "health_check",
            value=100.0,
            unit="pct",
            status="OK",
            provider="Datadog APM",
            timestamp=ts,
            formatted=f"{display_label} health probe: CPU utilization 24.1%, memory 38.0%, 0 active error spikes.",
            threshold=80.0,
            raw_payload={"cpu_pct": 24.1, "memory_pct": 38.0, "active_errors": 0},
        )

    def synthesize_claim(
        self,
        reading: TelemetryReading,
        entity_id: str | None = None,
    ) -> Claim:
        """
        Synthesize a Claim from a TelemetryReading.

        Attributed to the telemetry provider with epistemicStatus="TOOL_RESULT"
        and confidence=1.0. Strictly non-causal.
        """
        formatted_text = f"{reading.provider} telemetry: [{reading.status}] {reading.formatted}"

        # Epistemic discipline tripwire: Zero causal language
        if _CAUSAL_FORBIDDEN.search(formatted_text):
            raise ValueError(
                f"Rule 1 violation: probe text contains causal language: {formatted_text!r}"
            )

        claim_id = f"claim-probe-{int(time.time() * 1000)}-{reading.entity_id}"
        target_entity = entity_id or reading.entity_id

        return Claim(
            id=claim_id,
            text=formatted_text,
            epistemic_status="TOOL_RESULT",
            speaker_role=reading.provider,
            confidence=1.0,
            entity=target_entity,
            at=reading.timestamp,
            valid_from=reading.timestamp,
            ttl_seconds=300,
        )

    def catalog(self) -> dict[str, Any]:
        """Return the available telemetry catalog for discovery and inspector views."""
        return {
            key: {
                "label": val["label"],
                "provider": val["provider"],
                "defaultMetric": val["default_metric"],
                "metrics": list(val["metrics"].keys()),
            }
            for key, val in self._catalog.items()
        }


