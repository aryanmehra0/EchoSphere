"""
Active Telemetry Probing Engine — Domain Service.

Connects the incident bridge to read-only telemetry probes (Datadog APM,
Prometheus, and AWS CloudWatch).

── LIVE PROMETHEUS, WITH A STATIC FALLBACK ─────────────────────────────────
This catalog used to be the ENTIRE implementation: every value below
(`34.2`, `482.5`, ...) was returned verbatim with no network call, ever —
Echo's "Datadog/Prometheus" tool was a Python dict wearing a vendor's name.

`probe()` now tries a REAL query against Prometheus first (see
`app/infrastructure/prometheus_client.py` and `docker-compose.yml`'s
`telemetry`/`full` profile, which runs Prometheus, Loki, and a synthetic
data source emitting these same values for real). Only when that path is
unavailable — no `PROMETHEUS_URL` configured, or the server unreachable —
does this fall back to the catalog below, which exists now as a genuine
degrade path (matching this codebase's pattern for every other optional
piece of infrastructure: Redis, Qdrant, Postgres) rather than the only
thing that was ever there.

── WHY THIS DOES NOT BREAK RULE 1 ────────────────────────────────────────────
"Echo never asserts causation" is the governing rubric.
Telemetry probes report RAW READINGS, THRESHOLDS, and SYSTEM STATES only.
They NEVER output causal assertions ("This caused the outage", "Redis is the
root cause").
Claims generated by this engine are minted with:
  - epistemic_status = "TOOL_RESULT"
  - speaker_role = "Datadog APM" | "Prometheus" | "CloudWatch"
  - confidence = 1.0
This turns hypotheses ("Maybe Redis is out of memory") into settled facts
in 3 seconds, killing false rabbit holes without Echo ever diagnosing.
────────────────────────────────────────────────────────────────────────────
"""

